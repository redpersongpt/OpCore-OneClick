fn find_device(table: &[Device], id: u16) -> Option<Hit> {
    table.iter().find(|e| e.id == id).map(|e| Hit {
        family: e.family,
        igpu: family_is_igpu(e.family),
        name: e.name,
        kind: e.kind,
    })
}

fn find_range(table: &[Range], id: u16) -> Option<Hit> {
    table
        .iter()
        .find(|e| (e.lo..=e.hi).contains(&id))
        .map(|e| Hit {
            family: e.family,
            igpu: e.igpu,
            name: e.name,
            kind: e.kind,
        })
}

pub(super) fn intel(id: u16) -> Option<Hit> {
    find_device(INTEL_DEVICES, id).or_else(|| find_range(INTEL_RANGES, id))
}

pub(super) fn amd(id: u16) -> Option<Hit> {
    find_device(AMD_DEVICES, id).or_else(|| find_range(AMD_RANGES, id))
}

pub(super) fn nvidia(id: u16) -> Option<Hit> {
    find_device(NVIDIA_DEVICES, id).or_else(|| find_range(NVIDIA_RANGES, id))
}

/// Integrated graphics families (shared memory, part of the CPU or chipset).

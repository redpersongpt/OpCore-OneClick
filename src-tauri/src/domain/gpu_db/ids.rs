//! PCI id tables for GPU identification.
//!
//! Native ids follow Apple's driver match lists (as collected in OCLP
//! `pci_data.py`), fakes follow WhateverGreen's `devIntel[]` table and the
//! Dortania guides, GT levels follow Linux `include/drm/intel/pciids.h`, and
//! NVIDIA architecture ranges follow envytools / pci.ids chip assignments.

use crate::domain::model::GpuFamily::{self, *};

/// What macOS can do with one specific PCI id, on top of its family facts.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Kind {
    /// Family facts apply unchanged: Apple's driver matches the id, or the
    /// whole family has no driver anyway.
    Family,
    /// Not in Apple's id list; inject this device-id (WhateverGreen fake table
    /// or Dortania guide value).
    Fake(u16),
    /// Spoof target inferred from a sibling id; not documented upstream.
    FakeGuess(u16),
    /// Entry-level GT1 part with an optional spoof: works partially at best.
    Gt1(Option<u16>),
    /// Driver attaches for Quick Sync only; the part cannot drive a display.
    Headless,
    /// Compute / data-centre board without display outputs.
    Compute,
    /// Only NootRX drives it; the value is the WhateverGreen spoof alternative.
    NootRx(Option<u16>),
    /// No macOS driver for this id.
    NoDriver(&'static str),
}

pub(super) struct Device {
    pub id: u16,
    pub family: GpuFamily,
    pub name: &'static str,
    pub kind: Kind,
}

pub(super) struct Range {
    pub lo: u16,
    pub hi: u16,
    pub family: GpuFamily,
    pub igpu: bool,
    pub name: &'static str,
    pub kind: Kind,
}

/// Result of a PCI id lookup.
#[derive(Debug, Clone, Copy)]
pub(super) struct Hit {
    pub family: GpuFamily,
    pub igpu: bool,
    pub name: &'static str,
    pub kind: Kind,
}

const fn d(id: u16, family: GpuFamily, name: &'static str, kind: Kind) -> Device {
    Device {
        id,
        family,
        name,
        kind,
    }
}

const fn r(
    lo: u16,
    hi: u16,
    family: GpuFamily,
    igpu: bool,
    name: &'static str,
    kind: Kind,
) -> Range {
    Range {
        lo,
        hi,
        family,
        igpu,
        name,
        kind,
    }
}

